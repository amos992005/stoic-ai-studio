#!/usr/bin/env python3
"""
stoic-ai-studio :: Luca v2 orchestrator — "Luca Moretti" flagship character.

Reuses the hardened credential / metadata / push / poll / download / validate
logic from `scripts/run_kaggle_job.py` and swaps in the Luca kernel, artifact
manifest and metrics expectations.

Model weights are pulled from the HuggingFace hub inside Kaggle, but the *code*
still needs shipping: `kaggle kernels push` uploads only the single code file.
kaggle_kernel_luca/luca_studio.py is therefore generated by
scripts/build_luca_kernel.py with both workers embedded in it.

Every knob is env-overridable so the same code can be dry-run locally:

    KERNEL_SLUG                       default stoic-luca-studio
    KAGGLE_POLL_INTERVAL_SECONDS / KAGGLE_POLL_TIMEOUT_SECONDS
"""

from __future__ import annotations

import importlib.util
import os
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List

REPO_ROOT = Path(__file__).resolve().parent.parent

# --------------------------------------------------------------------------- #
# Phase 3 manifest
# --------------------------------------------------------------------------- #

KERNEL_SLUG = "stoic-luca-studio"
KERNEL_TITLE = KERNEL_SLUG
KERNEL_DIR = REPO_ROOT / "kaggle_kernel_luca"
CODE_FILE = "luca_studio.py"

#: Success = the full v2 pack: the master portrait, three scenes, the trained
#: adapter, the voice and the finished reel. Each is a separate deliverable from
#: one run.
#:
#: `luca_lora.safetensors` is required, not optional. It is the artifact that
#: makes the identity reproducible — without it the carousel is a set of four
#: one-off images, which is exactly what the LoRA upgrade was meant to stop
#: being the case. If training fails, the run must fail with it.
REQUIRED_ARTIFACTS: List[str] = [
    "01_luca_master.png",
    "02_luca_yacht.png",
    "03_luca_porsche.png",
    "04_luca_party.png",
    "luca_lora.safetensors",
    "luca_voice.wav",
    "luca_reel.mp4",
    "luca_metrics.json",
]
#: Warn only.
OPTIONAL_ARTIFACTS: List[str] = [
    "luca_raw.mp4",
    "dataset",
    "luca_metrics_images.json",
    "luca_metrics_video.json",
    "build.log",
]
#: Everything the workflow may commit back (5 MB per-file ceiling applies).
COMMITTABLE_ARTIFACTS: List[str] = [
    "outputs/01_luca_master.png",
    "outputs/02_luca_yacht.png",
    "outputs/03_luca_porsche.png",
    "outputs/04_luca_party.png",
    "outputs/luca_lora.safetensors",
    "outputs/luca_voice.wav",
    "outputs/luca_reel.mp4",
    "outputs/luca_metrics.json",
    "outputs/luca_metrics_images.json",
    "outputs/luca_metrics_video.json",
    "outputs/build.log",
]
#: Must exceed the kernel's own budget plus provisioning, the ~9 GB of weights
#: (SDXL + InstantID + Chatterbox + SadTalker + GFPGAN) and the artifact pull, or
#: we kill a kernel that is about to report success. The LoRA training loop adds
#: ~10 minutes on top of the previous 40.
POLL_TIMEOUT_SECONDS = int(os.environ.get("KAGGLE_POLL_TIMEOUT_SECONDS", str(75 * 60)))
#: Runtime guard for the warning only.
MAX_RUNTIME_SECONDS = 3900


#: `kaggle kernels push` uploads ONLY CODE_FILE, so the kernel is generated as a
#: self-contained script with the workers embedded (scripts/build_luca_kernel.py).
#: Staging siblings into the kernel directory is silently dropped, and a mounted
#: dataset only refreshes on a new dataset version — run 45949661268 mounted a
#: stale copy and re-ran the previous commit's bugs. Embedding has neither failure
#: mode.
BUILD_KERNEL = REPO_ROOT / "scripts" / "build_luca_kernel.py"


def build_kernel(orchestrator) -> None:
    """
    Regenerate kaggle_kernel_luca/luca_studio.py from scripts/luca_v2/.

    Runs every push: the generated file must never be able to lag its sources,
    which is exactly how a stale worker reached the GPU twice already.
    """
    orchestrator.log_group("regenerating the self-contained kernel")
    try:
        proc = subprocess.run([sys.executable, str(BUILD_KERNEL)],
                              capture_output=True, text=True, timeout=300)
        for line in ((proc.stdout or "") + (proc.stderr or "")).splitlines():
            orchestrator.log(line.strip())
        if proc.returncode != 0:
            raise RuntimeError(f"kernel build failed ({proc.returncode})")
    finally:
        orchestrator.log_group_end()

    # Fail here rather than after a Kaggle queue: the kernel must actually
    # contain both workers *and* the three modules they import, or the first
    # thing the run does is die on an ImportError.
    source = (KERNEL_DIR / CODE_FILE).read_text(encoding="utf-8")
    required = ("LUCA_COMMON_PY", "LUCA_CHARACTER_PY", "LUCA_LORA_PY",
                "GENERATE_IMAGES_PY", "GENERATE_VIDEO_PY", "FETCH_INSTANTID_PY",
                "INSTANTID_PIPELINE_PY", "def run_parallel", "def verify_embedded")
    missing = [token for token in required if token not in source]
    if missing:
        raise RuntimeError(f"generated kernel is missing {missing}")
    orchestrator.log(f"kernel verified: {len(source) / 1024:.0f} KB, 7 embedded "
                     f"sources and the parallel launcher present")


def load_orchestrator():
    """Import the Phase 1 orchestrator so every phase shares one code path."""
    path = REPO_ROOT / "scripts" / "run_kaggle_job.py"
    spec = importlib.util.spec_from_file_location("run_kaggle_job", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules["run_kaggle_job"] = module
    spec.loader.exec_module(module)
    return module


def main() -> int:
    orchestrator = load_orchestrator()

    orchestrator.KERNEL_SLUG = KERNEL_SLUG
    orchestrator.KERNEL_TITLE = KERNEL_TITLE
    orchestrator.KERNEL_DIR = KERNEL_DIR
    orchestrator.CODE_FILE = CODE_FILE
    orchestrator.EXPECTED_ARTIFACTS = list(REQUIRED_ARTIFACTS) + list(OPTIONAL_ARTIFACTS)
    orchestrator.REQUIRED_ARTIFACTS = list(REQUIRED_ARTIFACTS)
    orchestrator.OPTIONAL_ARTIFACTS = list(OPTIONAL_ARTIFACTS)
    orchestrator.COMMITTABLE_ARTIFACTS = list(COMMITTABLE_ARTIFACTS)
    # No dataset_sources: every weight is pulled from the public hub, and the
    # workers travel inside CODE_FILE itself.
    orchestrator.DEFAULT_DATASET_SOURCES = []
    orchestrator.POLL_TIMEOUT_SECONDS = POLL_TIMEOUT_SECONDS

    orchestrator.log("=" * 78)
    orchestrator.log("LUCA v2 · DUAL-GPU · MASTER + SCENES + VOICE + REEL")
    orchestrator.log(f"kernel: {KERNEL_DIR.relative_to(REPO_ROOT)}/{CODE_FILE}")
    orchestrator.log("=" * 78)

    if not (KERNEL_DIR / CODE_FILE).is_file():
        orchestrator.annotate_error(f"kernel source missing: {KERNEL_DIR / CODE_FILE}")
        return 2

    # --- generate the self-contained kernel before the push ---------------- #
    try:
        build_kernel(orchestrator)
    except Exception as exc:
        orchestrator.annotate_error(f"could not generate the kernel: {exc}")
        return 2

    exit_code = orchestrator.main()
    if exit_code == 0:
        summarize(orchestrator)
    return exit_code


def summarize(orchestrator) -> None:
    """Print a compact success summary from the two v2 metrics halves."""
    import json

    metrics_path = orchestrator.OUTPUT_DIR / "luca_metrics.json"
    if not metrics_path.is_file():
        orchestrator.log("luca_metrics.json missing from outputs", "WARN")
        return
    try:
        data: Dict[str, Any] = json.loads(metrics_path.read_text(encoding="utf-8"))
    except Exception as exc:
        orchestrator.log(f"could not read luca_metrics.json: {exc}", "WARN")
        return

    images = data.get("images") or {}
    video = data.get("video") or {}

    if images:
        orchestrator.log(
            f"images: {images.get('status')} in {images.get('total_seconds')}s "
            f"on {images.get('device')} · {images.get('base_model')}"
        )

        dataset = images.get("dataset") or {}
        orchestrator.log(
            f"  dataset: {dataset.get('images')} image(s) via "
            f"{dataset.get('method')} · master face "
            f"{dataset.get('master_face')}"
        )

        training = images.get("training") or {}
        if training:
            orchestrator.log(
                f"  LoRA: r={training.get('rank')} alpha={training.get('alpha')} "
                f"· {training.get('max_train_steps')} steps @ "
                f"{training.get('resolution')}px on {training.get('images')} "
                f"image(s) · {training.get('train_seconds')}s · "
                f"loss {training.get('loss_first_25')}→"
                f"{training.get('loss_last_25')} "
                f"({'' if training.get('loss_decreasing') else 'NOT '}decreasing) "
                f"· {training.get('adapter_mb')} MB"
            )
        else:
            orchestrator.log("  LoRA: NOT TRAINED — carousel fell back to the "
                             "base model", "ERROR")

        carousel = images.get("carousel") or {}
        orchestrator.log(
            f"  carousel: {len(carousel.get('files') or [])} image(s) · "
            f"lora_used={carousel.get('lora_used')} · "
            f"instantid_at_inference="
            f"{(images.get('prohibitions_honoured') or {}).get('instantid_at_inference')}"
        )
        scale = (images.get("identity") or {}).get("lora_scale")
        orchestrator.log(
            f"  identity: trigger={(images.get('identity') or {}).get('trigger_word')} "
            f"age={(images.get('identity') or {}).get('age')} "
            f"lora_scale={scale}"
        )
        for name in carousel.get("files") or []:
            orchestrator.log(f"    • {name}")

    if video:
        voice = video.get("voice") or {}
        probe = video.get("reel_probe") or {}
        video_stream = probe.get("video") or {}
        audio_stream = probe.get("audio") or {}
        sync = probe.get("sync") or {}
        orchestrator.log(
            f"voice: {voice.get('duration_s')}s @ {voice.get('sample_rate')} Hz · "
            f"{voice.get('class')} t3={voice.get('dtype')} "
            f"s3gen={voice.get('s3gen_dtype')}"
        )
        orchestrator.log(
            f"reel: {video_stream.get('width')}x{video_stream.get('height')} "
            f"{video_stream.get('codec')}/{video_stream.get('pix_fmt')} + "
            f"{audio_stream.get('codec')} · {probe.get('duration_s')}s · "
            f"drift {sync.get('drift_s')}s · "
            f"iPhone-compatible={probe.get('iphone_compatible')}"
        )
        sadtalker = video.get("sadtalker") or {}
        orchestrator.log(
            f"sadtalker: size {sadtalker.get('size')} · "
            f"preprocess {sadtalker.get('preprocess')} · "
            f"enhancer {sadtalker.get('enhancer')} · "
            f"enhanced={sadtalker.get('enhanced')} · still={sadtalker.get('still')}"
        )

    artifacts = data.get("artifacts") or []
    orchestrator.log(f"artifacts reported by the workers: {artifacts}")
    missing = [a for a in REQUIRED_ARTIFACTS
               if not (orchestrator.OUTPUT_DIR / a).is_file()]
    if missing:
        orchestrator.log(f"REQUIRED artifacts missing: {missing}", "ERROR")
    else:
        orchestrator.log("all required artifacts present")


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(130)
    except Exception as exc:  # pragma: no cover - last-resort guard
        import traceback

        traceback.print_exc()
        print(f"::error::luca orchestrator crashed: {type(exc).__name__}: {exc}", flush=True)
        sys.exit(1)
