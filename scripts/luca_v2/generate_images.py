INSTANTID_ADAPTER = "ip-adapter.bin"
INSTANTID_CONTROLNET = "ControlNetModel"

DEVICE = "cuda:0"
DATASET_DIR = OUTPUT_DIR / "dataset"
LORA_FILENAME = "luca_lora.safetensors"
MASTER_FILENAME = "01_luca_master.png"

#: Everything the carousel needs. Deliberately NOT including training deps.
IMAGE_DEPS = ["compel>=2.0.2", "einops", "onnx==1.23.2",
              "onnxruntime-gpu==1.22.0", "opencv-python-headless"]
TRAIN_DEPS = ["peft>=0.13", "accelerate>=1.0", "safetensors"]
INSTANTID_DEPS = ["insightface==2.1"] + ["scikit-image", "requests", "scipy"]

