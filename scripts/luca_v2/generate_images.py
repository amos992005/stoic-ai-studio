def face_providers() -> List[str]:
    """CUDA when onnxruntime actually exposes it, else CPU."""
    try:
        import onnxruntime as ort

        available = list(ort.get_available_providers())
    except Exception as exc:
        log(f"onnxruntime unavailable: {exc}", "WARN")
        return ["CPUExecutionProvider"]
    wanted = [p for p in available if "CUDA" in p][:1] + ["CPUExecutionProvider"]
    log(f"onnxruntime providers available={available} → using={wanted}")
    return wanted


def load_face_app(root: Path):
    """antelopev2 — the 512-d face encoder InstantID is trained against."""
    import shutil

    from huggingface_hub import hf_hub_download

    files = ("scrfd_10g_bnkps.onnx", "glintr100.onnx", "1k3d68.onnx",
             "2d106det.onnx", "genderage.onnx")
    model_dir = root / "models" / "antelopev2"
    if not all((model_dir / name).is_file() for name in files):
        model_dir.mkdir(parents=True, exist_ok=True)
        for name in files:
            local = hf_hub_download("DIAMONIK7777/antelopev2", name)
            shutil.copy2(local, model_dir / name)
        log(f"antelopev2 staged ({model_dir})")

    from insightface.app import FaceAnalysis

    app = FaceAnalysis(name="antelopev2", root=str(root),
                       providers=face_providers())
    app.prepare(ctx_id=0, det_size=(640, 640))
    return app


#: Detection scales, largest first. antelopev2's detector is the SCRFD-10G that
#: InstantID itself uses; it is trained on faces occupying a decent share of the
#: frame, and at det_size 640 a medium or full body shot leaves far too few
#: pixels on the face to find. Run 45980957305 lost 12 of 15 dataset images this
#: way — the same detector that found the close-up master missed everything
#: wider than a head-and-shoulders crop.
DET_SIZES = ((640, 640), (1024, 1024))


def detect_face(app, image_rgb):
    """
    The largest male face, or the largest face if none scores male.

    Detection escalates rather than giving up: a smaller det_size is the cheaper
    attempt, a larger one costs ~2.5x the compute but resolves faces that are
    small in frame. Giving up after one scale is what silently shrank the
    training set to three images.
    """
    import cv2
    import numpy as np

    array = image_rgb if isinstance(image_rgb, np.ndarray) else np.asarray(image_rgb)
    bgr = cv2.cvtColor(array, cv2.COLOR_RGB2BGR)

    faces = []
    used = None
    for det_size in DET_SIZES:
        try:
            app.prepare(ctx_id=0, det_size=det_size)
        except Exception:
            pass
        faces = app.get(bgr)
        used = det_size
        if faces:
            break

    # restore the default so the next call does not inherit the widened scale
    if used != DET_SIZES[0]:
        try:
            app.prepare(ctx_id=0, det_size=DET_SIZES[0])
        except Exception:
            pass

    if not faces:
        return None, 0
    males = [f for f in faces if getattr(f, "sex", None) == "M"] or faces
    best = max(males, key=lambda f: float((f.bbox[2] - f.bbox[0]) *
                                          (f.bbox[3] - f.bbox[1])))
    return best, len(faces)


def load_instantid(timings: Dict[str, float]):
    """SDXL + InstantID as a community pipeline, for the dataset stage only."""
    import torch
    from diffusers.models import ControlNetModel

    from fetch_instantid import ensure_pipeline

    sys.path.insert(0, str(ensure_pipeline().parent))
    from instantid_pipeline import StableDiffusionXLInstantIDPipeline, draw_kps

    with timed("load_instantid", timings):
        controlnet = ControlNetModel.from_pretrained(
            INSTANTID_REPO, subfolder=INSTANTID_CONTROLNET,
            torch_dtype=torch.float16)
        pipe = StableDiffusionXLInstantIDPipeline.from_pretrained(
            BASE_MODEL, controlnet=controlnet, torch_dtype=torch.float16,
            variant="fp16", use_safetensors=True)
        from huggingface_hub import hf_hub_download

        pipe.load_ip_adapter_instantid(hf_hub_download(INSTANTID_REPO,
                                                       INSTANTID_ADAPTER))

        if hasattr(pipe.vae, "enable_slicing"):
            pipe.vae.enable_slicing()
        pipe.to(DEVICE)

        # image_proj_model is created by load_ip_adapter_instantid(), after
        # __init__, so it is not in pipe.components and pipe.to() never touches
        # it. Left alone it stays on CPU and the first identity call dies on a
        # device mismatch.
        projector = getattr(pipe, "image_proj_model", None)
        if projector is not None:
            projector.to(DEVICE, dtype=pipe.unet.dtype)
        try:
            pipe.set_progress_bar_config(disable=True)
        except Exception:
            pass
        log(f"InstantID ready on {DEVICE} · vae slicing on · "
            f"projector on {DEVICE}")
    return pipe, draw_kps


def build_compel(pipe):
    from compel import CompelForSDXL

    return CompelForSDXL(pipe)


def encode(compel, prompt: str):
    """The four SDXL tensors, from compel (no 77-token truncation)."""
    conditioning = compel(prompt, negative_prompt=character.NEGATIVE_PROMPT)
    return {
        "prompt_embeds": conditioning.embeds,
        "pooled_prompt_embeds": conditioning.pooled_embeds,
        "negative_prompt_embeds": conditioning.negative_embeds,
        "negative_pooled_prompt_embeds": conditioning.negative_pooled_embeds,
    }


def set_scheduler(pipe) -> None:
    from diffusers import DPMSolverMultistepScheduler

    pipe.scheduler = DPMSolverMultistepScheduler.from_config(
        pipe.scheduler.config, use_karras_sigmas=True,
        algorithm_type="dpmsolver++", solver_order=2)


def build_master(timings: Dict[str, float]) -> Dict[str, Any]:
    """
    Stage 1a: the one portrait that defines him, with no reference at all.

    This has to come first and has to be plain SDXL: InstantID is a *reference*
    model, so it cannot be the thing that invents the face it anchors to.
    """
    import torch
    from diffusers import StableDiffusionXLPipeline

    summary: Dict[str, Any] = {"file": MASTER_FILENAME}
    DATASET_DIR.mkdir(parents=True, exist_ok=True)

    with timed("build_master", timings):
        pipe = StableDiffusionXLPipeline.from_pretrained(
            BASE_MODEL, torch_dtype=torch.float16, variant="fp16",
            use_safetensors=True).to(DEVICE)
        if hasattr(pipe.vae, "enable_slicing"):
            pipe.vae.enable_slicing()
        set_scheduler(pipe)
        compel = build_compel(pipe)

        master_prompt = character.check_prompt(
            f"{character.SUBJECT}, {MASTER_PROMPT_SUFFIX}")
        image = pipe(
            **encode(compel, master_prompt),
            width=1024, height=1024, num_inference_steps=30, guidance_scale=3.8,
            generator=torch.Generator(device=DEVICE).manual_seed(42),
        ).images[0]
        master_path = OUTPUT_DIR / MASTER_FILENAME
        image.save(master_path, format="PNG", optimize=True)
        stats = image_stats(image)
        if is_degenerate(stats):
            raise RuntimeError(f"the master portrait is degenerate ({stats}) — "
                               f"process 2 would animate a flat frame")
        summary["stats"] = stats
        log(f"master portrait written ({master_path.stat().st_size / 1024:.0f} KB, "
            f"std {stats['std']})")
        summary["prompt"] = master_prompt
        summary["bytes"] = master_path.stat().st_size

    # Free the plain pipeline before InstantID allocates its ControlNet.
    del pipe, compel
    gc.collect()
    torch.cuda.empty_cache()
    return summary


def build_dataset(timings: Dict[str, float], master_path: Path) -> Dict[str, Any]:
    """
    Stage 1b: 15 varied photographs of the *same* person, anchored by InstantID.

    Variety is what the LoRA learns from. Fifteen close-ups would teach it one
    crop; fifteen framings, lightings and expressions teach it the face.
    """
    import torch

    summary: Dict[str, Any] = {
        "images": 0,
        "files": [],
        "unverified": [],
        "method": "master from RealVisXL, 15 variants anchored by InstantID",
        "instantid_scales": {"ip_adapter": DATASET_IP_SCALE,
                             "controlnet": DATASET_CONTROLNET_SCALE},
    }

    with timed("build_dataset", timings):
        root = Path(os.environ.get("FACE_MODEL_ROOT", "/kaggle/working/face_models"))
        app = load_face_app(root)
        # NB: `__import__("PIL.Image").Image` is the *class*, not the module —
        # Pillow sets `PIL.Image.Image` as an attribute of itself. Import the
        # module explicitly. (Run 45980036759 died on exactly this.)
        from PIL import Image as PilImage

        master = PilImage.open(master_path)
        master_face, found = detect_face(app, master)
        if master_face is None:
            raise RuntimeError("no face detected in the master portrait")
        log(f"master identity locked: {found} face(s), "
            f"bbox={[int(v) for v in master_face.bbox]}")
        summary["master_face"] = {"detected": found,
                                  "bbox": [int(v) for v in master_face.bbox],
                                  "det_size": [int(v) for v in master_face.bbox[2:]]}

        pipe, draw_kps = load_instantid(timings)
        compel = build_compel(pipe)
        face_emb = master_face.normed_embedding
        face_kps = draw_kps(master, master_face.kps)
        pipe.set_ip_adapter_scale(DATASET_IP_SCALE)

        for index, entry in enumerate(character.DATASET, start=1):
            prompt = character.dataset_prompt(entry)
            path = DATASET_DIR / f"{entry['name']}.png"
            image = pipe(
                **encode(compel, prompt),
                image_embeds=face_emb, image=face_kps,
                width=DATASET_SIZE[0], height=DATASET_SIZE[1],
                num_inference_steps=DATASET_STEPS, guidance_scale=DATASET_CFG,
                controlnet_conditioning_scale=DATASET_CONTROLNET_SCALE,
                generator=torch.Generator(device=DEVICE).manual_seed(int(entry["seed"])),
            ).images[0]
            image.save(path, format="PNG", optimize=True)

            # The detector is a *quality signal on the finished image*, not a
            # filter on the pipeline. InstantID has already anchored the face, so
            # a detection miss means the framing is wide, not that the image is
            # unusable — and deleting it is how the training set collapsed.
            # Keep everything, and record which images verified so a genuinely
            # faceless render is still visible in the metrics.
            face, _ = detect_face(app, image)
            if face is None:
                summary["unverified"].append(path.name)
                log(f"  [{index}/{len(character.DATASET)}] {path.name} "
                    f"({path.stat().st_size / 1024:.0f} KB) · face not detected "
                    f"in-frame, kept", "WARN")
            else:
                summary["files"].append(path.name)
                log(f"  [{index}/{len(character.DATASET)}] {path.name} "
                    f"({path.stat().st_size / 1024:.0f} KB)")

        summary["images"] = len(summary["files"]) + len(summary["unverified"])
        log(f"dataset complete: {summary['images']} images in {DATASET_DIR} "
            f"({len(summary['files'])} face-verified, "
            f"{len(summary['unverified'])} unverified)")

        # Drop the reference model here rather than in the caller: the ControlNet
        # and the projection network are the two largest residents on the card,
        # and training cannot coexist with them.
        del pipe, compel, app, draw_kps
        gc.collect()

    return summary


def unload_instantid(timings: Dict[str, float]) -> Dict[str, Any]:
    """
    Give the VRAM back before training asks for it.

    InstantID's ControlNet plus its 1.7 GB projection network are the two
    largest residents on a 14.5 GB T4, and the training UNet with activations
    and gradient checkpointing does not fit alongside them. Both references are
    dropped *and* the allocator is emptied, because `del` alone leaves the blocks
    cached and `torch.cuda.memory_allocated` keeps reporting them as used by this
    process.
    """
    import torch

    freed: Dict[str, Any] = {}
    with timed("unload_instantid", timings):
        gc.collect()
        torch.cuda.empty_cache()
        try:
            free, total = torch.cuda.mem_get_info(0)
            freed = {"free_mb": round(free / 1024 ** 2), "total_mb": round(total / 1024 ** 2)}
            log(f"after InstantID unload: {freed['free_mb']} MB free "
                f"of {freed['total_mb']} MB")
        except Exception:
            log("after InstantID unload (mem_get_info unavailable)")
    return freed


