def main() -> int:
    started = time.perf_counter()
    telemetry = Tee(BUILD_LOG, sys.stdout)
    sys.stdout = telemetry  # type: ignore[assignment]

    timings: Dict[str, float] = {}
    metrics: Dict[str, Any] = {
        "process": "images",
        "device": DEVICE,
        "status": "running",
        "started_at": ts(),
        "pipeline": "character LoRA (dataset → train → carousel, no InstantID at inference)",
        "base_model": BASE_MODEL,
        "identity": {
            "method": "SDXL LoRA on the UNet (instantid only builds the dataset)",
            "trigger_word": character.TRIGGER,
            "age": character.AGE,
            "description": character.SUBJECT,
            "lora_scale": LORA_SCALE,
        },
        "prohibitions_honoured": {
            "celebrity_name_in_prompts": False,
            "instantid_at_inference": False,
            "pipe.to_cpu": False,
            "inswapper_128": False,
            "svd_xt": False,
            "sdxl_img2img_adetailer": False,
        },
        "timings_seconds": timings,
        "errors": [],
        "artifacts": [],
    }
    exit_code = 0

    try:
        ensure_deps(timings)

        import torch

        metrics["environment"] = {
            "python": sys.version.split()[0],
            "torch": torch.__version__,
            "diffusers": __import__("diffusers").__version__,
            "peft": __import__("peft").__version__,
            "cuda_available": torch.cuda.is_available(),
        }
        log(f"environment: {json.dumps(metrics['environment'])}")
        if not torch.cuda.is_available():
            raise RuntimeError("no CUDA device — enable a Kaggle GPU accelerator")
        torch.cuda.set_device(0)

        # ---- 1. dataset ---------------------------------------------------- #
        # Three distinct lifetimes, so three distinct scopes: the master is plain
        # SDXL, the variants are InstantID, and by the time training starts
        # neither pipeline is still resident.
        metrics["master"] = build_master(timings)
        metrics["artifacts"].append(MASTER_FILENAME)

        dataset = build_dataset(timings, OUTPUT_DIR / MASTER_FILENAME)
        metrics["dataset"] = dataset

        metrics["vram_after_unload"] = unload_instantid(timings)

        # ---- 2. train ------------------------------------------------------ #
        lora_path: Optional[Path] = OUTPUT_DIR / LORA_FILENAME
        if dataset["images"] >= 8:
            try:
                metrics["training"] = luca_lora.train(
                    image_paths=[DATASET_DIR / name for name in dataset["files"]],
                    prompts=[character.dataset_prompt(entry)
                             for entry in character.DATASET
                             if entry["name"] in
                             {Path(n).stem for n in dataset["files"]}],
                    base_model=BASE_MODEL, lora_path=lora_path, device=DEVICE,
                    resolution=TRAIN_RESOLUTION, rank=LORA_RANK, alpha=LORA_ALPHA,
                    learning_rate=TRAIN_LR, max_train_steps=TRAIN_STEPS,
                )
                metrics["artifacts"].append(LORA_FILENAME)
            except Exception as exc:
                # A failed adapter is not a failed run: the carousel can be
                # generated without it, and saying so is more useful than a
                # stack trace with no images.
                detail = f"{type(exc).__name__}: {exc}"
                log(f"LoRA training failed — carousel will use the base model: "
                    f"{detail}", "ERROR")
                metrics["errors"].append({"stage": "train", "error": detail})
                lora_path = None
        else:
            log(f"only {dataset['images']} dataset images — need at least 8 to "
                f"train, skipping", "ERROR")
            metrics["errors"].append({"stage": "train",
                                      "error": "insufficient dataset"})
            lora_path = None

        # ---- 3. carousel ---------------------------------------------------- #
        carousel = build_carousel(timings, lora_path)
        metrics["carousel"] = carousel
        metrics["artifacts"].extend(carousel["files"])

        log("image pipeline complete — LoRA identity, no face swap, "
            "no adetailer, no CPU offload")

    except Exception as exc:
        detail = f"{type(exc).__name__}: {exc}"
        log(f"FATAL — {detail}", "ERROR")
        log(traceback.format_exc(), "ERROR")
        metrics["status"] = "failed"
        metrics["errors"].append({"stage": "fatal", "error": detail})
        exit_code = 1
    finally:
        metrics["total_seconds"] = round(time.perf_counter() - started, 1)
        metrics["finished_at"] = ts()
        if metrics["status"] == "running":
            metrics["status"] = "success" if not metrics["errors"] else "success_with_errors"
        merge_metrics("images", metrics, METRICS_PATH)

        log("=" * 74)
        log(f"image pipeline status: {metrics['status']} · "
            f"{metrics['total_seconds']}s")
        for name in metrics["artifacts"]:
            path = OUTPUT_DIR / name
            log(f"  {'✓' if path.is_file() else '✗'} {name}"
                + (f" ({path.stat().st_size / 1024:.0f} KB)" if path.is_file() else ""))
        log("=" * 74)
        sys.stdout = telemetry._stream  # type: ignore[assignment]
        telemetry.close()

    return exit_code


if __name__ == "__main__":
    sys.exit(main())
