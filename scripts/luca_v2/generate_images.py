#: final carousel — that is plain SDXL + LoRA.
DATASET_IP_SCALE = 0.80
DATASET_CONTROLNET_SCALE = 0.55
DATASET_STEPS = 28
DATASET_CFG = 4.0
DATASET_SIZE = (832, 1024)

#: Nano-banana sanity check on how much framing text the LoRA learns from.
MASTER_PROMPT_SUFFIX = ("close-up portrait facing the camera, soft window light, "
                        "relaxed neutral expression, plain white linen shirt, "
                        "no hands near the face, blurred Mediterranean harbour "
                        "behind him")

TRAIN_STEPS = int(os.environ.get("LUCA_TRAIN_STEPS", "400"))
TRAIN_RESOLUTION = int(os.environ.get("LUCA_TRAIN_RESOLUTION", "768"))
TRAIN_LR = float(os.environ.get("LUCA_TRAIN_LR", "1e-4"))
LORA_RANK = int(os.environ.get("LUCA_LORA_RANK", "16"))
LORA_ALPHA = int(os.environ.get("LUCA_LORA_ALPHA", "16"))
LORA_SCALE = float(os.environ.get("LUCA_LORA_SCALE", "0.85"))
CAROUSEL_STEPS = int(os.environ.get("LUCA_CAROUSEL_STEPS", "30"))
CAROUSEL_CFG = float(os.environ.get("LUCA_CAROUSEL_CFG", "4.0"))


