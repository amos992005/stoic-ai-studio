def check_no_meta(pipe) -> None:
    """
    Fail early if any UNet parameter is a placeholder.

    A ``meta`` parameter holds no storage, and ``.to()`` on one raises
    "Cannot copy out of meta tensor; no data!". That is what the adapter load
    reported in run 45999895543, and the message says nothing about where the
    real problem is.
    """
    meta = [name for name, parameter in pipe.unet.named_parameters()
            if getattr(parameter, "is_meta", False)]
    if meta:
        raise RuntimeError(
            f"{len(meta)} UNet parameters are placeholders on the 'meta' device "
            f"(first: {meta[0]}) — the pipeline was not materialised")


def load_adapter(pipe, lora_path: Path) -> Tuple[bool, str]:
    """
    Attach the trained adapter, trying the two loaders that can do it.

    diffusers' own loader first. If it refuses — which it does when the state
    dict is peft-shaped rather than diffusers-shaped, and the error surfaces as
    a meta-tensor copy — the adapter is split per attention module and applied
    through peft directly, which is the shape ``luca_lora.save_adapter``
    actually wrote.
    """
    try:
        check_no_meta(pipe)
    except RuntimeError as exc:
        log(str(exc), "ERROR")
        return False, str(exc)

    try:
        pipe.load_lora_weights(str(lora_path.parent), weight_name=lora_path.name,
                               adapter_name="luca")
        pipe.set_adapters(["luca"], [LORA_SCALE])
        return True, "diffusers.load_lora_weights"
    except Exception as exc:
        log(f"diffusers LoRA loader refused ({type(exc).__name__}: {exc}) — "
            f"retrying through peft", "WARN")

    try:
        from safetensors.torch import load_file

        state = load_file(str(lora_path))
        loaded = _peft_fallback(pipe, state)
        if loaded == 0:
            return False, "peft fallback matched no attention modules"
        pipe.set_adapters(["luca"], [LORA_SCALE])
        return True, f"peft direct ({loaded} modules)"
    except Exception as exc:
        return False, f"{type(exc).__name__}: {exc}"


def _peft_fallback(pipe, state: Dict[str, Any]) -> int:
    """
    Attach our adapter without diffusers' loader.

    ``luca_lora.save_adapter`` writes keys of the form
    ``unet.<module path>.lora_A.default.weight`` (and the B side), tensors in
    float32. Each one belongs to exactly one linear layer in the UNet, so the
    adapter can be rebuilt per module with peft's ``LoraLayer`` (r=rank,
    alpha=alpha) and the weights copied in. Returns how many modules were
    matched.
    """
    import re

    from peft import LoraConfig
    from peft.tuners.lora.layer import Linear as LoraLinearLayer

    entries: Dict[str, Dict[str, Any]] = {}
    pattern = re.compile(r"^unet\.(?P<module>.+)\.lora_(?P<side>[AB])\."
                         r"(?:default\.)?weight$")
    for key, tensor in state.items():
        match = pattern.match(key)
        if not match:
            continue
        module = match.group("module")
        entries.setdefault(module, {})[match.group("side")] = tensor

    rank = LORA_RANK
    for sides in entries.values():
        if "A" in sides:
            rank = int(sides["A"].shape[0])
            break

    modules = dict(pipe.unet.named_modules())
    attached = 0
    for module_name, sides in entries.items():
        target = modules.get(module_name)
        if target is None or "A" not in sides or "B" not in sides:
            continue
        try:
            # peft >=0.15 takes the config explicitly; older signatures inferred
            # it. Build one per module so the tuner knows what it is wrapping.
            config = LoraConfig(r=rank, lora_alpha=LORA_ALPHA, lora_dropout=0.0,
                                target_modules=[module_name.rsplit(".", 1)[-1]])
            layer = LoraLinearLayer(target, "luca", config=config, r=rank,
                                    lora_alpha=LORA_ALPHA)
            layer.update_layer("luca", r=rank, lora_alpha=LORA_ALPHA,
                               config=config, lora_dropout=0.0,
                               init_lora_weights=False)
            with __import__("torch").no_grad():
                layer.lora_A["luca"].weight.copy_(sides["A"])
                layer.lora_B["luca"].weight.copy_(sides["B"])
            parent_name, _, child = module_name.rpartition(".")
            parent = modules[parent_name]
            setattr(parent, child, layer)
            attached += 1
        except Exception as exc:
            log(f"  peft fallback skipped {module_name}: {exc}", "WARN")
            continue
    log(f"peft fallback attached {attached}/{len(entries)} adapter modules "
        f"(r={rank}, alpha={LORA_ALPHA})")
    return attached


def cast_lora_to_unet(pipe) -> Dict[str, Any]:
    """
    Move every adapter tensor onto the UNet's dtype and device, explicitly.

    ``luca_lora.save_adapter`` stores float32 (that is what keeps training
    numerically sane), and a float32 LoRA multiplied into a float16 UNet can
    produce infinities that the VAE decodes to a flat frame.

    The first attempt at this looked only for ``module.lora_A`` dicts and found
    zero tensors (run 45995210057 logged ``tensors: 0``), because which
    attribute holds the adapter depends on whether diffusers loaded it through
    its own ``LoraLayer`` or through peft's wrapper. So the scan is by *name*
    over parameters and buffers — ``lora_A``, ``lora_B``, ``lora_embedding_A``,
    ``.default.weight``, whatever the loader produced — and it also handles the
    plain-dict and single-module shapes for good measure.
    """
    import torch

    unet = pipe.unet
    dtype, device = unet.dtype, unet.device
    census: Dict[str, int] = {}
    for name, parameter in unet.named_parameters():
        if "lora" in name.lower() and parameter.dtype != dtype:
            parameter.data = parameter.data.to(device=device, dtype=dtype)
            census[f"param:{parameter.dtype}"] = census.get(f"param:{parameter.dtype}", 0) + 1
    for name, buffer in unet.named_buffers():
        if "lora" in name.lower() and buffer.dtype.is_floating_point and buffer.dtype != dtype:
            buffer.data = buffer.data.to(device=device, dtype=dtype)

    # Belt and braces: some loaders attach the layers outside the module tree.
    moved = 0
    for module in unet.modules():
        for attribute in ("lora_A", "lora_B", "lora_embedding_A", "lora_embedding_B"):
            container = getattr(module, attribute, None)
            if container is None:
                continue
            layers = (container.values() if isinstance(container, dict)
                      else [container])
            for layer in layers:
                if hasattr(layer, "to"):
                    layer.to(device=device, dtype=dtype)
                    moved += 1

    lora_tensors = [(name, parameter.dtype)
                    for name, parameter in unet.named_parameters()
                    if "lora" in name.lower()]
    summary = {
        "unet_dtype": str(dtype),
        "lora_tensors": len(lora_tensors),
        "lora_dtypes": sorted({str(d) for _, d in lora_tensors}),
        "layers_touched": moved,
        "dtype_census": census,
    }
    log(f"adapter cast: {summary}")
    if not lora_tensors:
        log("no LoRA parameters found in the UNet — the adapter did not attach",
            "ERROR")
    return summary


def image_stats(image) -> Dict[str, Any]:
    """Cheap degeneracy check: a flat frame means the decode produced NaN."""
    import numpy as np

    array = np.asarray(image.convert("RGB"), dtype=np.float32)
    return {
        "mean": round(float(array.mean()), 2),
        "std": round(float(array.std()), 2),
        "unique_colors": int(len(np.unique(array.reshape(-1, 3), axis=0))),
    }


def is_degenerate(stats: Dict[str, Any]) -> bool:
    """
    A real photograph has thousands of colours and a standard deviation in the
    tens. A NaN decode collapses to one value.
    """
    return stats["std"] < 8.0 or stats["unique_colors"] < 2000


def build_carousel(timings: Dict[str, float], lora_path: Optional[Path]
                   ) -> Dict[str, Any]:
    """
    The four finals: RealVisXL + LoRA. No InstantID, no ControlNet, no reference.

    This is where the trained weights pay off — and it is easier to get right
    than the InstantID path, because a plain SDXL pipeline has no
    `image`/`image_embeds` contract to satisfy.
    """
    import torch
    from diffusers import StableDiffusionXLPipeline

    produced: Dict[str, Any] = {"files": [], "lora_used": bool(lora_path)}

    with timed("load_carousel_pipe", timings):
        pipe = StableDiffusionXLPipeline.from_pretrained(
            BASE_MODEL, torch_dtype=torch.float16, variant="fp16",
            use_safetensors=True).to(DEVICE)
        if hasattr(pipe.vae, "enable_slicing"):
            pipe.vae.enable_slicing()
        set_scheduler(pipe)

        if lora_path is not None and lora_path.is_file():
            load_ok, how = load_adapter(pipe, lora_path)
            produced["lora_load"] = how
            if load_ok:
                produced["adapter_cast"] = cast_lora_to_unet(pipe)
                log(f"LoRA loaded from {lora_path.name} at scale {LORA_SCALE} "
                    f"via {how}")
            else:
                log(f"LoRA could not be applied ({how}) — falling back to the "
                    f"un-adapted model", "ERROR")
                produced["lora_used"] = False
        else:
            log("no adapter available — generating with the base model", "WARN")

        # Compel after the adapter: it reads the text encoders, not the UNet,
        # but building it once here keeps the load order obvious.
        compel = build_compel(pipe)

    adapter_attached = produced["lora_used"]
    used_scale = LORA_SCALE
    for entry in character.CAROUSEL:
        prompt = character.carousel_prompt(entry)
        with timed(f"generate_{entry['file']}", timings):
            image = pipe(
                **encode(compel, prompt),
                width=int(entry["size"][0]), height=int(entry["size"][1]),
                num_inference_steps=CAROUSEL_STEPS, guidance_scale=CAROUSEL_CFG,
                generator=torch.Generator(device=DEVICE).manual_seed(int(entry["seed"])),
            ).images[0]
            stats = image_stats(image)

            # A degenerate frame means the adapter is poisoning this prompt, not
            # that the prompt is wrong. Walk the scale down before giving up on
            # it, and *never* unload the adapter for the whole carousel: run
            # 45995210057 did exactly that on slide 01, so slides 02-04 were
            # rendered by the base model and the carousel lost its identity.
            if is_degenerate(stats) and adapter_attached:
                for scale in LORA_FALLBACK_SCALES:
                    log(f"{entry['file']}: degenerate at scale {scale} "
                        f"({stats}) — retrying lower", "WARN")
                    try:
                        pipe.set_adapters(["luca"], [scale])
                    except Exception as exc:
                        log(f"could not lower the adapter scale: {exc}", "WARN")
                        break
                    image = pipe(
                        **encode(compel, prompt),
                        width=int(entry["size"][0]),
                        height=int(entry["size"][1]),
                        num_inference_steps=CAROUSEL_STEPS,
                        guidance_scale=CAROUSEL_CFG,
                        generator=torch.Generator(device=DEVICE).manual_seed(
                            int(entry["seed"])),
                    ).images[0]
                    stats = image_stats(image)
                    if not is_degenerate(stats):
                        used_scale = scale
                        break
                else:
                    log(f"{entry['file']}: still degenerate at every adapter "
                        f"scale — rendering it with the base model", "ERROR")
                    produced.setdefault("degenerate_with_lora", []).append(
                        str(entry["file"]))
                    try:
                        pipe.unload_lora_weights()
                    except Exception as exc:
                        log(f"could not unload the adapter: {exc}", "WARN")
                    adapter_attached = False
                    image = pipe(
                        **encode(compel, prompt),
                        width=int(entry["size"][0]),
                        height=int(entry["size"][1]),
                        num_inference_steps=CAROUSEL_STEPS,
                        guidance_scale=CAROUSEL_CFG,
                        generator=torch.Generator(device=DEVICE).manual_seed(
                            int(entry["seed"])),
                    ).images[0]
                    stats = image_stats(image)

            if is_degenerate(stats):
                raise RuntimeError(
                    f"{entry['file']} is degenerate even without the LoRA "
                    f"({stats}) — the pipeline, not the adapter, is broken")

            path = OUTPUT_DIR / str(entry["file"])
            image.save(path, format="PNG", optimize=True)
            produced["files"].append(str(entry["file"]))
            produced.setdefault("stats", {})[str(entry["file"])] = stats
            produced.setdefault("scales", {})[str(entry["file"])] = (
                used_scale if adapter_attached else None)
            log(f"wrote {path.name} ({path.stat().st_size / 1024:.0f} KB) · "
                f"{entry['size'][0]}x{entry['size'][1]} · seed {entry['seed']} "
                f"· std {stats['std']} · lora_scale "
                f"{used_scale if adapter_attached else 'off'}")

    del pipe, compel
    gc.collect()
    torch.cuda.empty_cache()
    return produced


