def ensure_deps(timings: Dict[str, float]) -> None:
    """
    Install what is missing, in the order that cannot break the runtime.

    insightface is installed ``--no-deps`` and *after* the headless opencv: its
    wheel declares the GUI opencv, which imports libGL and is absent on Kaggle,
    and a normal resolve would also let it downgrade numpy under torch.
    """
    with timed("pip_install_deps", timings):
        missing = missing_packages(IMAGE_DEPS + TRAIN_DEPS)
        if missing:
            plain = [m for m in missing if not m.startswith("insightface")]
            if plain and not pip_install(plain):
                raise RuntimeError("dependency install failed — see above")
        if missing_packages(INSTANTID_DEPS):
            if not pip_install(["insightface==2.1"], no_deps=True):
                raise RuntimeError("insightface install failed — see above")
            pip_install([m for m in INSTANTID_DEPS if not m.startswith("insightface")])
            pip_install(["--force-reinstall", "--no-deps", "opencv-python-headless"])
        for module in ("cv2", "insightface", "compel", "diffusers", "peft"):
            __import__(module)
        log("image dependencies import cleanly")


