"""
Luca Moretti — Process 1 of 2: character LoRA on cuda:0.

One run, three stages, in this order and for these reasons:

  1. DATASET   A clean 27-year-old master portrait, then 15 varied photographs of
               the same person via InstantID. InstantID is a *reference* model:
               it needs an existing face to anchor to, which is why the master
               comes first and why it cannot be the thing that generates the
               final carousel.

  2. TRAINING  Once the 15 images exist the identity can live in the weights
               instead of in a per-image adapter. InstantID is unloaded
               completely — both its ControlNet and its 1.7 GB projection
               network — before a single training step, because on a 14.5 GB T4
               the training UNet, its activations and a resident ControlNet do
               not coexist.

  3. CAROUSEL  The four finals are generated by RealVisXL + the trained LoRA and
               *nothing else*. No InstantID, no ControlNet, no reference image.
               That is the entire point of training: the identity is in the
               weights, so the pipeline is plain SDXL and every prompt is free to
               put him anywhere.

The third stage deliberately runs even if training failed — a carousel from the
base model without the adapter is still a usable carousel, and it is honest
about what it is (``lora_used: false`` in the metrics).
"""

