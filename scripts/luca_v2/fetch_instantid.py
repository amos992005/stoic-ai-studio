#!/usr/bin/env python3
"""
Fetch the InstantID diffusers pipeline and write a traceable header.

InstantID is not part of diffusers core: it lives in
`examples/community/pipeline_stable_diffusion_xl_instantid.py` in the diffusers
repo, and is *not* shipped inside the pip wheel. The previous runs died because
a hand-written import of something "not in core" was assumed to exist, so this
bootstrapper is explicit about where the file comes from and fails loudly with a
usable message instead of an ImportError deep inside a worker.

Order of attempts:
  1. a vendored copy committed next to this script (`_vendor/`), if present
  2. the same file from the diffusers tag matching the installed version
  3. the diffusers `main` copy

The written module is imported as `instantid_pipeline`.
"""

from __future__ import annotations

import importlib.util
import sys
import urllib.error
import urllib.request
from pathlib import Path

VENDOR_DIR = Path(__file__).resolve().parent
TARGET = VENDOR_DIR / "instantid_pipeline.py"
COMMITTED = VENDOR_DIR / "_vendor" / "pipeline_stable_diffusion_xl_instantid.py"
MODULE_URL = (
    "https://raw.githubusercontent.com/huggingface/diffusers/{ref}"
    "/examples/community/pipeline_stable_diffusion_xl_instantid.py"
)

#: Upstream pins these; the file is a diffusers community pipeline and tracks
#: the pipeline internals closely.
REQUIRED_SYMBOLS = (
    "class StableDiffusionXLInstantIDPipeline",
    "def draw_kps",
    "load_ip_adapter_instantid",
)


def _version_tag() -> str:
    try:
        import diffusers

        return f"v{diffusers.__version__}"
    except Exception:
        return "main"


def _download(url: str, timeout: int = 120) -> str:
    with urllib.request.urlopen(url, timeout=timeout) as response:
        return response.read().decode("utf-8")


def _with_header(source: str) -> str:
    return (
        "# Generated by scripts/luca_v2/fetch_instantid.py\n"
        "# Source: huggingface/diffusers examples/community/\n"
        "# pipeline_stable_diffusion_xl_instantid.py\n"
        "# Do not edit: re-run the bootstrapper instead.\n"
        + source
    )


def _validate(source: str) -> None:
    missing = [symbol for symbol in REQUIRED_SYMBOLS if symbol not in source]
    if missing:
        raise RuntimeError(
            f"downloaded InstantID pipeline is missing {missing} — the upstream "
            "file changed shape, so the call sites in generate_images.py need "
            "reviewing before this can run"
        )


def ensure_pipeline(force: bool = False) -> Path:
    """
    Materialise instantid_pipeline.py next to this file and return its path.

    The committed copy under `_vendor/` is the primary source: a GPU run should
    never depend on reaching raw.githubusercontent.com. Network fetch is only a
    fallback for when the vendored file is absent or explicitly refreshed.
    """
    if not force and COMMITTED.is_file():
        _validate(COMMITTED.read_text(encoding="utf-8"))
        if not TARGET.is_file() or \
                TARGET.read_text(encoding="utf-8") != _with_header(COMMITTED.read_text(encoding="utf-8")):
            TARGET.write_text(
                _with_header(COMMITTED.read_text(encoding="utf-8")), encoding="utf-8")
        print(f"[instantid] using committed vendored pipeline ({COMMITTED.name})",
              flush=True)
        return TARGET

    if TARGET.is_file() and not force:
        _validate(TARGET.read_text(encoding="utf-8"))
        print(f"[instantid] using existing pipeline: {TARGET}", flush=True)
        return TARGET

    attempts = []
    tag = _version_tag()
    for ref in (tag, "main"):
        url = MODULE_URL.format(ref=ref)
        try:
            print(f"[instantid] fetching pipeline from {ref}", flush=True)
            source = _download(url)
            _validate(source)
            TARGET.write_text(_with_header(source), encoding="utf-8")
            print(f"[instantid] wrote {TARGET} ({len(source) / 1024:.0f} KB) "
                  f"from ref={ref}", flush=True)
            return TARGET
        except urllib.error.HTTPError as exc:
            attempts.append(f"{ref}: HTTP {exc.code}")
        except Exception as exc:
            attempts.append(f"{ref}: {type(exc).__name__}: {exc}")
        print(f"[instantid] ref={ref} failed: {attempts[-1]}", flush=True)

    raise SystemExit(
        "could not obtain the InstantID diffusers pipeline.\n"
        f"  target: {TARGET}\n"
        "  attempts:\n    " + "\n    ".join(attempts) + "\n"
        "  fix: vendor the file manually into "
        f"{TARGET.parent} or re-run with network access."
    )


def _import_check(path: Path) -> None:
    """
    Prove the pipeline *imports*, but only if its runtime deps are present.

    The launcher runs this before either worker, i.e. before `pip install
    opencv/diffusers`. Importing unconditionally would abort the whole run on
    Kaggle with a bare ModuleNotFoundError for a dependency the worker is about
    to install. The file's correctness is still checked by _validate(); the
    import test is a bonus that only applies in a provisioned environment.
    """
    missing = [m for m in ("cv2", "diffusers", "insightface", "torch")
               if importlib.util.find_spec(m) is None]
    if missing:
        print(f"[instantid] import check skipped — not installed yet: "
              f"{', '.join(missing)} (the worker installs these)", flush=True)
        return

    sys.path.insert(0, str(path.parent))
    import instantid_pipeline  # noqa: F401  (import check only)
    print(f"[instantid] import OK: {instantid_pipeline.__file__}", flush=True)


if __name__ == "__main__":
    _path = ensure_pipeline(force="--force" in sys.argv)
    _import_check(_path)
