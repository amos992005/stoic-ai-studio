#!/usr/bin/env python3
"""
Regenerate `kaggle_kernel_luca/luca_studio.py` as a single self-contained script.

Why this exists
---------------
`kaggle kernels push` reliably uploads exactly one thing: the code file. Every
attempt to get *sibling* files into the kernel has failed in a different way —
staging them into the kernel directory is silently dropped, and a dataset mount
only refreshes on a new dataset version (run 45949661268 mounted a stale copy and
re-ran the previous commit's bugs).

So the kernel is generated instead: the two workers, the InstantID bootstrapper
and the vendored pipeline are embedded verbatim as string constants and written
to /kaggle/working at startup. One file in, one working directory out.

The sources remain the single source of truth — this dataset is regenerated from
them and should never be hand-edited. `--check` fails if it is out of date, which
is what CI runs.
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys
from typing import Dict

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
WORKER_DIR = REPO_ROOT / "scripts" / "luca_v2"
TARGET = REPO_ROOT / "kaggle_kernel_luca" / "luca_studio.py"

#: constant name → source file. Embedded in this order.
EMBEDDED: Dict[str, str] = {
    "GENERATE_IMAGES_PY": "generate_images.py",
    "GENERATE_VIDEO_PY": "generate_video.py",
    "FETCH_INSTANTID_PY": "fetch_instantid.py",
    "INSTANTID_PIPELINE_PY": "_vendor/pipeline_stable_diffusion_xl_instantid.py",
}

HEADER = '''"""
Luca Moretti · v2 — the single file Kaggle executes.

GENERATED by scripts/build_luca_kernel.py — do not edit by hand. The workers,
the InstantID bootstrapper and the vendored pipeline are embedded at the bottom
of this file and written to disk at startup, because `kaggle kernels push`
uploads only the code file and nothing else survives the trip.

    python generate_images.py &     # cuda:0 · SDXL + InstantID
    python generate_video.py  &     # cuda:1 · Chatterbox -> MuseTalk -> mp4
    wait
"""

from __future__ import annotations

import ast
import os
import re
import subprocess
import sys
import threading
import traceback
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict

OUTPUT_DIR = Path(os.environ.get("OUTPUT_DIR", "/kaggle/working"))
WORKER_DIR = Path(os.environ.get("LUCA_WORKER_DIR", "/kaggle/working/luca_workers"))

#: Banned tokens, checked against both workers before any GPU work starts.
#: Matched against executable source only — see `_executable_source`.
BANNED = {
    'pipe.to("cpu")': "CPU offload is prohibited",
    "inswapper_128": "inswapper_128 is prohibited",
    "StableVideoDiffusion": "SVD-XT is prohibited",
    "stable-video-diffusion": "SVD-XT is prohibited",
    "StableDiffusionXLImg2ImgPipeline": "SDXL img2img Adetailer is prohibited",
}

#: Lines that merely *report* the prohibition (a metrics dict, a log line) are
#: not offences. An offence is an executable call or an import.
ALLOWED_PATTERNS = (
    re.compile(r'^\\s*"[^"]*"\\s*:\\s*False\\s*,?\\s*$'),        # "x": False,
    re.compile(r"^\\s*'[^']*'\\s*:\\s*False\\s*,?\\s*$"),
)


def ts() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def banner(message: str, level: str = "INFO") -> None:
    print(f"[{ts()}] [{level:<5}] [launcher] {message}", flush=True)


def _executable_source(source: str) -> str:
    """
    Drop everything that is documentation or a report of the ban.

    Both workers *state* the prohibitions in their module docstring and *report*
    them in a metrics dict (`"inswapper_128": False`), so a naive substring scan
    rejects the very files that comply. Docstrings go via the AST, comment-only
    lines by prefix, self-reporting lines by pattern.
    """
    try:
        tree: ast.AST | None = ast.parse(source)
    except SyntaxError:
        tree = None

    if tree is not None:
        docstrings = set()
        for node in ast.walk(tree):
            if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef,
                                 ast.AsyncFunctionDef)):
                doc = ast.get_docstring(node, clean=False)
                if doc:
                    docstrings.add(doc)
        for doc in docstrings:
            source = source.replace(doc, "")

    kept = []
    for line in source.splitlines():
        if line.strip().startswith("#"):
            continue
        if any(pattern.match(line) for pattern in ALLOWED_PATTERNS):
            continue
        kept.append(line)
    return "\\n".join(kept)


def stage_workers() -> Path:
    """
    Write the embedded sources to disk, next to each other.

    Kaggle runs this file from /kaggle/src/script.py, which is on *this*
    interpreter's path but is not importable by a child process, and the child
    needs its siblings (`instantid_pipeline`, `fetch_instantid`) resolvable by
    plain `import`. Writing them into one directory and running from there is
    what makes that work.
    """
    WORKER_DIR.mkdir(parents=True, exist_ok=True)

    for name, payload in (
        ("generate_images.py", GENERATE_IMAGES_PY),
        ("generate_video.py", GENERATE_VIDEO_PY),
        ("fetch_instantid.py", FETCH_INSTANTID_PY),
    ):
        destination = WORKER_DIR / name
        destination.write_text(payload, encoding="utf-8")
        banner(f"wrote {name} ({destination.stat().st_size / 1024:.1f} KB)")

    # The vendored pipeline, in the layout fetch_instantid.py expects, so the
    # bootstrapper never needs the network.
    vendor = WORKER_DIR / "_vendor"
    vendor.mkdir(parents=True, exist_ok=True)
    vendored = vendor / "pipeline_stable_diffusion_xl_instantid.py"
    vendored.write_text(INSTANTID_PIPELINE_PY, encoding="utf-8")
    banner(f"wrote _vendor/{vendored.name} "
           f"({vendored.stat().st_size / 1024:.1f} KB)")

    return WORKER_DIR


def verify_embedded() -> None:
    """Fail before any GPU work if the payload did not survive embedding."""
    problems = []
    checks = (
        ("generate_images.py", "def generate_master", 0),
        ("generate_images.py", "InstantX/InstantID", 0),
        ("generate_video.py", "def synth_voice", 0),
        ("generate_video.py", "def run_musetalk", 0),
        ("fetch_instantid.py", "def ensure_pipeline", 0),
        ("_vendor/pipeline_stable_diffusion_xl_instantid.py",
         "class StableDiffusionXLInstantIDPipeline", 0),
        ("_vendor/pipeline_stable_diffusion_xl_instantid.py", "def draw_kps", 0),
    )
    for relative, needle, _ in checks:
        path = WORKER_DIR / relative
        if not path.is_file():
            problems.append(f"{relative}: missing after staging")
            continue
        if needle not in path.read_text(encoding="utf-8"):
            problems.append(f"{relative}: does not contain {needle!r}")
    if problems:
        raise SystemExit("embedded worker payload is corrupt:\\n  "
                         + "\\n  ".join(problems))
    banner("embedded payload verified: both workers, bootstrapper and vendored "
           "pipeline are intact on disk")


def check_prohibitions(workdir: Path) -> None:
    """Fail fast if a banned construct reappeared in either worker."""
    offenders = []
    for name in ("generate_images.py", "generate_video.py"):
        code = _executable_source((workdir / name).read_text(encoding="utf-8"))
        for token, reason in BANNED.items():
            if token in code:
                offenders.append(f"{name}: {token} — {reason}")
    if offenders:
        raise SystemExit("prohibited constructs present:\\n  " + "\\n  ".join(offenders))
    banner("prohibition check passed: no pipe.to('cpu'), inswapper, SVD-XT or "
           "img2img adetailer in either worker")


def preflight_instantid(workdir: Path) -> None:
    """
    Materialise the InstantID community pipeline before the GPU work starts.

    Importing it lazily inside the worker would waste the SDXL load time before
    failing; this runs the bootstrapper outright.
    """
    proc = subprocess.run(
        [sys.executable, "fetch_instantid.py"],
        cwd=str(workdir), capture_output=True, text=True,
    )
    output = (proc.stdout or "") + (proc.stderr or "")
    for line in output.strip().splitlines():
        banner(line.strip())
    if proc.returncode != 0:
        raise SystemExit("InstantID pipeline bootstrap failed — see above")


def run_parallel(workdir: Path) -> Dict[str, int]:
    """
    The whole point: both pipelines live at the same time on separate GPUs.

        python generate_images.py & python generate_video.py & wait
    """
    base_env = dict(os.environ)
    base_env["PYTHONUNBUFFERED"] = "1"
    base_env["OUTPUT_DIR"] = str(OUTPUT_DIR)
    # Keep fragmentation from turning a 14.5 GB card into a 12 GB one.
    base_env.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

    # One GPU each, enforced by the OS rather than trusted to set_device().
    # Both children used to inherit CUDA_VISIBLE_DEVICES=0,1 and rely on
    # torch.cuda.set_device(1); third-party code that allocates without an
    # explicit device (MuseTalk's torch.load(..., map_location=None)) then landed
    # on GPU 0 and OOM'd against the image pipeline (run 45956577517 — the very
    # steps that had passed a run earlier). Hiding the other card makes that
    # impossible: inside each worker its own GPU is the only one, always cuda:0.
    envs = {
        "images": {**base_env, "CUDA_VISIBLE_DEVICES": "0"},
        "video": {**base_env, "CUDA_VISIBLE_DEVICES": "1"},
    }

    commands = {
        "images": [sys.executable, "generate_images.py"],
        "video": [sys.executable, "generate_video.py"],
    }
    banner("=" * 70)
    banner("launching both pipelines in parallel")
    banner(f"  images → physical GPU 0 (cuda:0) : {' '.join(commands['images'])}")
    banner(f"  video  → physical GPU 1 (cuda:0) : {' '.join(commands['video'])}")
    banner("=" * 70)

    procs = {}
    for name, command in commands.items():
        procs[name] = subprocess.Popen(
            command, cwd=str(workdir), env=envs[name],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, bufsize=1,
        )
        banner(f"started {name} (pid {procs[name].pid})")

    # Stream both logs as they arrive so a stalled run is diagnosable.
    def pump(name: str, proc) -> None:
        prefix = f"[{name}] "
        for line in iter(proc.stdout.readline, ""):
            sys.stdout.write(prefix + line)
            sys.stdout.flush()

    threads = [threading.Thread(target=pump, args=(n, p), daemon=True)
               for n, p in procs.items()]
    for thread in threads:
        thread.start()

    exit_codes: Dict[str, int] = {}
    for name, proc in procs.items():
        exit_codes[name] = proc.wait()
        banner(f"{name} exited with code {exit_codes[name]}",
               "INFO" if exit_codes[name] == 0 else "ERROR")
    for thread in threads:
        thread.join(timeout=30)
    return exit_codes


def main() -> int:
    banner("=" * 70)
    banner("stoic-ai-studio · LUCA v2 · parallel dual-GPU architecture")
    banner("=" * 70)

    try:
        workdir = stage_workers()
        verify_embedded()
        check_prohibitions(workdir)
        preflight_instantid(workdir)
        exit_codes = run_parallel(workdir)

        images_ok = exit_codes.get("images") == 0
        video_ok = exit_codes.get("video") == 0
        banner(f"summary: images={'ok' if images_ok else 'FAILED'} "
               f"video={'ok' if video_ok else 'FAILED'}")

        # Report what actually landed on disk.
        for name in ("01_luca_master.png", "02_luca_yacht.png",
                     "03_luca_porsche.png", "04_luca_party.png",
                     "luca_voice.wav", "luca_reel.mp4"):
            path = OUTPUT_DIR / name
            banner(f"  {'✓' if path.is_file() else '✗'} {name}"
                   + (f" ({path.stat().st_size / 1024:.0f} KB)"
                      if path.is_file() else ""))

        if not images_ok:
            banner("image pipeline failed — the carousel is the deliverable",
                   "ERROR")
            return 1
        if not video_ok:
            # The reel is the second half of one run, not a separate deliverable.
            banner("video pipeline failed — carousel artifacts are still valid",
                   "WARN")
            return 0
        return 0

    except SystemExit as exc:
        banner(str(exc), "ERROR")
        return 2
    except Exception as exc:
        banner(f"launcher crashed: {type(exc).__name__}: {exc}", "ERROR")
        for line in traceback.format_exc().splitlines():
            banner(line, "ERROR")
        return 2


'''

#: Appended after the embedded sources: `main()` reads those constants, so the
#: entrypoint must come last. Putting it earlier raises NameError on the very
#: first call to stage_workers() (run 45950387190).
TRAILER = '''
if __name__ == "__main__":
    sys.exit(main())
'''

FOOTER_HEADER = """
# =========================================================================== #
# Embedded worker sources — GENERATED, do not edit.
# =========================================================================== #
"""


def wrap(name: str, source: str, origin: str) -> str:
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()[:16]
    if '"""' in source:
        # A triple-quoted literal cannot be embedded verbatim; use repr().
        literal = repr(source)
        return (f"#: {origin} · sha256:{digest}\n"
                f"{name} = {literal}\n")
    return (f'{name} = r"""# {origin} · sha256:{digest}\n{source}"""\n')


def build() -> str:
    missing = [str(WORKER_DIR / src) for src in EMBEDDED.values()
               if not (WORKER_DIR / src).is_file()]
    if missing:
        raise SystemExit(f"cannot embed, sources missing: {missing}")

    parts = [HEADER, FOOTER_HEADER]
    for constant, relative in EMBEDDED.items():
        source = (WORKER_DIR / relative).read_text(encoding="utf-8")
        parts.append(wrap(constant, source, f"scripts/luca_v2/{relative}"))
    parts.append(TRAILER)
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the generated kernel is out of date")
    args = parser.parse_args()

    rendered = build()
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""

    if args.check:
        if rendered != current:
            print(f"{TARGET.relative_to(REPO_ROOT)} is stale — run "
                  f"scripts/build_luca_kernel.py", file=sys.stderr)
            return 1
        print(f"{TARGET.relative_to(REPO_ROOT)} is up to date "
              f"({len(rendered) / 1024:.0f} KB)")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(rendered, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO_ROOT)} ({len(rendered) / 1024:.0f} KB, "
          f"{len(EMBEDDED)} embedded source(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
